# A hero's stars as the game draws them: five six-petal stars, one petal per step, lit from
# the top petal counter-clockwise; six steps make a star (the data's 0 to 30).
def stars_of(steps):
    out = ''
    for star in range(5):
        lit = max(0, min(6, steps - 6 * star))
        petals = ''.join(f'<path class="{"on" if petal < lit else "off"}" transform="rotate({-60 * petal})" d="M0 -1.2 L2.3 -5.4 L0 -10 L-2.3 -5.4 Z"/>'
                         for petal in range(6))
        out += f'<svg viewBox="-11 -11 22 22" aria-hidden="true">{petals}</svg>'
    return f'<span class="stars" title="{steps // 6}-Star{f" ({steps % 6} of 6)" if steps % 6 else ""}">{out}</span>'

