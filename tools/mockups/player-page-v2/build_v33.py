def short(n):
    for size, unit in ((1e9, 'B'), (1e6, 'M'), (1e3, 'K')):
        if n >= size:
            v = n / size
            return (f'{v:.2f}' if v < 10 else f'{v:.1f}' if v < 100 else f'{v:.0f}') + unit
    return f'{n:,}'

