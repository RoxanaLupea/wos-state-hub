def board(label, value, rank):
    # A board: its short name, then its value with its rank small after it.
    v = value if value is not None else '<span class="empty">–</span>'
    r = f'<span class="r">#{rank}</span>' if rank else ''
    return f'<span class="cap">{SHORT.get(label, label)}</span><span class="v">{v}{r}</span>'

def fig(label, value, rank, cls='fig'):
    r = f'<span class="r">#{rank}</span>' if rank else ''
    v = value if value is not None else '<span class="empty">–</span>'
    return f'<div class="{cls}"><span class="cap">{label}</span><span class="v"><b>{v}</b>{r}</span></div>'

def troops_part(c, mode, changed_to=None):
    if c['troops'] is None:
        return '<section class="troops"><h2>Troops</h2><p class="nodata">The game data has no troops for this chief.</p></section>'
    exalted = [t[2] == 12 for t in c['troops']]
    skills = list(c['skills'])
    if mode == 'edit':
        rows = ''
        for i, (n, k, tier, fcl) in enumerate(c['troops']):
            if not exalted[i]:
                continue
            level = changed_to[i] if changed_to else skills[i]
            opts = ''.join(f'<button type="button" class="lvl{" on" if v == level else ""}">{"None" if v is None else f"Lvl. {v}"}</button>'
                           for v in (None, 1, 2, 3))
            rows += (f'<div class="erow"><div class="art troop small"><img class="p" src="images/troops/{k}-exalted.png" alt="">'
                     f'<img class="fc" src="images/troops/fc{fcl}.png" alt=""></div>'
                     f'<span class="tname">{n}</span><div class="lvls">{opts}</div></div>')
        save_on = changed_to is not None and changed_to != skills
        return (f'<section class="troops open"><h2>Troops</h2>'
                f'<div class="erows">{rows}</div><div class="saverow"><button type="button" class="ghost-button">Cancel</button>'
                f'<button type="button" class="primary-button save"{"" if save_on else " disabled"}>Save</button></div></section>')
    items = ''
    for i, (n, k, tier, fcl) in enumerate(c['troops']):
        key, word = TIER.get(tier, (None, f'T{tier}'))
        # Below T10: the tier's portrait where the repo has it (Marksmen T1 to T9 so far).
        if key is None and (here / f'images/troops/{k}-t{tier}.png').exists():
            key = f't{tier}'
        detail = f'<span class="q">{word}</span>'
        if tier == 12 and skills[i]:
            detail += f'<span class="s">Lvl. {skills[i]}</span>'
        # Below Tier 10 there is no portrait in the repo: the name and tier only.
        art = (f'<div class="art troop"><img class="p" src="images/troops/{k}-{key}.png" alt="">'
               + (f'<img class="fc" src="images/troops/fc{fcl}.png" alt="">' if fcl else '') + '</div>') if key else ''
        items += (f'<div class="item">{art}'
                  f'<span class="tname">{n}</span><span class="detail">{detail}</span></div>')
    # Only the skill levels of Exalted troops can be set here, so the line shows only with them.
    note = ''
    if mode == 'ask':
        note = '<p class="note">Set the skill levels of your Exalted troops.</p>'
    if mode == 'before':
        note = '<p class="note">Before State of Power on Mon 30 Nov, check that the skill levels of your Exalted troops are up to date.</p>'
    update = f'<button type="button" class="more update" aria-expanded="false">Update troops{CHEVRON}</button>' if any(exalted) and c['own'] else ''
    return f'<section class="troops"><h2>Troops</h2><div class="items three">{items}</div>{note}{update}</section>'

